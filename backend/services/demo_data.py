def _id() -> str:
    return str(uuid.uuid4())


def _demo_doc(**fields):
    return {"id": _id(), "is_demo": True, "created_at": now(), **fields}


async def _demo_exists() -> bool:
    for collection in CREATE_ORDER:
        if await db[collection].find_one({"is_demo": True}, {"_id": 1}):
            return True
    return False


async def _rollback(created: dict[str, list[str]]) -> None:
    for collection in reversed(CREATE_ORDER):
        ids = created.get(collection, [])
        if ids:
            await db[collection].delete_many({"id": {"$in": ids}})


