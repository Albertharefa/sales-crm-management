async def _find_production_reference(collection: str, query: dict) -> bool:
    return await db[collection].find_one({"is_demo": {"$ne": True}, **query}, {"_id": 1}) is not None


async def clear_demo_data() -> dict:
    demo_users = await db.users.find({"is_demo": True}, {"id": 1, "user_id": 1, "name": 1}).to_list(1000)
    demo_customers = await db.customers.find({"is_demo": True}, {"id": 1, "customer_id": 1, "name": 1}).to_list(1000)
    demo_products = await db.products.find({"is_demo": True}, {"id": 1, "code": 1}).to_list(1000)
    demo_opportunities = await db.opportunities.find({"is_demo": True}, {"id": 1, "opportunity_id": 1, "name": 1}).to_list(1000)
    demo_quotations = await db.quotations.find({"is_demo": True}, {"id": 1, "number": 1}).to_list(1000)

    if not any([demo_users, demo_customers, demo_products, demo_opportunities, demo_quotations]):
        return {"deleted": {name: 0 for name in CLEAR_ORDER}}

    user_ids = [item["id"] for item in demo_users]
    user_names = [item.get("name") for item in demo_users if item.get("name")]
    customer_ids = [item["id"] for item in demo_customers]
    customer_names = [item.get("name") for item in demo_customers if item.get("name")]
    product_ids = [item["id"] for item in demo_products]
    opportunity_ids = [item["id"] for item in demo_opportunities]
    opportunity_names = [item.get("name") for item in demo_opportunities if item.get("name")]
    quotation_numbers = [item["number"] for item in demo_quotations if item.get("number")]

    # Abort if a non-demo production document references demo entities.
    reference_checks = [
        ("customers", {"$or": [{"sales_id": {"$in": user_ids}}, {"sales_name": {"$in": user_names}}]}),
        ("opportunities", {"$or": [{"sales_id": {"$in": user_ids}}, {"sales_name": {"$in": user_names}}, {"customer_id": {"$in": customer_ids}}, {"customer_name": {"$in": customer_names}}]}),
        ("activities", {"$or": [{"sales_id": {"$in": user_ids}}, {"sales_name": {"$in": user_names}}, {"customer_id": {"$in": customer_ids}}, {"customer_name": {"$in": customer_names}}, {"opportunity_id": {"$in": opportunity_ids}}]}),
        ("quotations", {"$or": [{"sales_id": {"$in": user_ids}}, {"sales_name": {"$in": user_names}}, {"customer_id": {"$in": customer_ids}}, {"customer_name": {"$in": customer_names}}, {"opportunity_id": {"$in": opportunity_ids}}]}),
        ("purchase_orders", {"$or": [{"sales_id": {"$in": user_ids}}, {"sales_name": {"$in": user_names}}, {"customer_id": {"$in": customer_ids}}, {"customer_name": {"$in": customer_names}}, {"quotation_number": {"$in": quotation_numbers}}]}),
        ("sales_targets", {"$or": [{"sales_id": {"$in": user_ids}}, {"sales_name": {"$in": user_names}}]}),
        ("tasks", {"$or": [{"assigned_user": {"$in": user_names}}, {"customer_name": {"$in": customer_names}}, {"opportunity_name": {"$in": opportunity_names}}]}),
        ("quotations", {"items.product_id": {"$in": product_ids}}),
        ("purchase_orders", {"items.product_id": {"$in": product_ids}}),
    ]
    for collection, query in reference_checks:
        if await _find_production_reference(collection, query):
            raise ValueError(f"Clear Dummy dibatalkan: masih ada data production yang mereferensikan demo pada collection {collection}.")

    deleted: dict[str, int] = {}
    for collection in CLEAR_ORDER:
        result = await db[collection].delete_many({"is_demo": True})
        deleted[collection] = int(result.deleted_count)
    return {"deleted": deleted}
